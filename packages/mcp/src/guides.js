/**
 * One guide's text, or null when the name is not a guide. Case and spaces are
 * forgiven (`Optimistic UI` finds `optimistic-ui`).
 * @param {string} name
 * @returns {string | null}
 */
export function guide(name) {
  const key = String(name ?? '').trim().toLowerCase().replace(/[\s_]+/g, '-');
  return Object.hasOwn(GUIDES, key) ? GUIDES[key].text : null;
}
