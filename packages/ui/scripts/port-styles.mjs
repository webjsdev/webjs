#!/usr/bin/env node
/**
 * Port shadcn/ui's style files into the kit (#1666, D8).
 *
 *   node packages/ui/scripts/port-styles.mjs <shadcn>/apps/v4/registry/styles
 *
 * Copies `style-<name>.css` for each of shadcn's eight styles into
 * packages/registry/styles/, unchanged, then appends one block: the BASE
 * SUPPLEMENT from packages/registry/styles/supplement.json.
 *
 * The supplement exists because the kit's base form is not quite shadcn's.
 * Each kit component keeps inline only the classes shadcn's base form ALSO
 * keeps, so that the default `new-york` style reproduces the kit's existing
 * look exactly. Where shadcn's base form carries a layout utility the kit
 * never had (`select-none` on a button), that utility is recorded in the
 * supplement and added to every ported style here instead, so a shadcn style
 * renders the way shadcn renders it. Marker classes (`group/button`) cannot
 * ride `@apply`, so those stay inline in the components and are not here.
 *
 * shadcn/ui is MIT licensed; see packages/ui/THIRD_PARTY_NOTICES.md.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC = process.argv[2];
if (!SRC) {
  console.error('usage: node packages/ui/scripts/port-styles.mjs <shadcn>/apps/v4/registry/styles');
  process.exit(1);
}
const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '..', 'packages', 'registry', 'styles');
export const PORTED_STYLES = ['vega', 'nova', 'maia', 'lyra', 'mira', 'luma', 'sera', 'rhea'];

const supplement = JSON.parse(readFileSync(join(OUT, 'supplement.json'), 'utf8'));

for (const name of PORTED_STYLES) {
  const original = readFileSync(join(SRC, `style-${name}.css`), 'utf8').trimEnd();
  let block = `\n\n/* MARK: WebJs base supplement. Layout utilities shadcn's base form keeps
   inline and the kit's base form does not, added here so this style renders
   as it does in shadcn/ui. Generated by packages/ui/scripts/port-styles.mjs
   from styles/supplement.json; do not edit by hand. */\n.style-${name} {\n`;
  for (const [cnName, classes] of Object.entries(supplement)) {
    block += `  .${cnName} {\n    @apply ${classes};\n  }\n`;
  }
  block += '}\n';
  const header = `/* Ported from shadcn/ui (apps/v4/registry/styles/style-${name}.css, MIT).
   Regenerate with packages/ui/scripts/port-styles.mjs. */\n`;
  writeFileSync(join(OUT, `style-${name}.css`), header + original + block);
}
console.log(`ported ${PORTED_STYLES.length} styles with ${Object.keys(supplement).length} supplement rule(s)`);
