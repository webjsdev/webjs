/**
 * A bar chart with an active bar, a chart block ported from shadcn/ui's chart-bar-active.
 *
 * Installed by `npx @webjsdev/ui add chart-bar-active` at
 * `components/charts/chart-bar-active.ts`. It is app code you own, so edit it
 * freely, and render it from any page with `${ChartBarActive()}`.
 */
import { html, svg } from '@webjsdev/core';
import { cn } from '../../lib/utils.ts';
import {
  cardClass, cardContentClass, cardDescriptionClass, cardFooterClass, cardHeaderClass, cardTitleClass,
} from '../../components/card.ts';
import { barChart, chartRectangle, type ChartConfig } from '../../components/chart.ts';

const chartData = [
  { browser: 'chrome', visitors: 187, fill: 'var(--color-chrome)' },
  { browser: 'safari', visitors: 200, fill: 'var(--color-safari)' },
  { browser: 'firefox', visitors: 275, fill: 'var(--color-firefox)' },
  { browser: 'edge', visitors: 173, fill: 'var(--color-edge)' },
  { browser: 'other', visitors: 90, fill: 'var(--color-other)' },
];

const chartConfig = {
  visitors: {
    label: 'Visitors',
  },
  chrome: {
    label: 'Chrome',
    color: 'var(--chart-1)',
  },
  safari: {
    label: 'Safari',
    color: 'var(--chart-2)',
  },
  firefox: {
    label: 'Firefox',
    color: 'var(--chart-3)',
  },
  edge: {
    label: 'Edge',
    color: 'var(--chart-4)',
  },
  other: {
    label: 'Other',
    color: 'var(--chart-5)',
  },
} satisfies ChartConfig;

// lucide's trending-up, the icon in shadcn's footer.
const TrendingUp = (cls = '') => svg`<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" class=${'lucide lucide-trending-up ' + cls}><path d="M16 7h6v6"></path><path d="m22 7-8.5 8.5-5-5L2 17"></path></svg>`;

const ACTIVE_INDEX = 2;

export default function ChartBarActive() {
  return html`
    <div data-slot="card" class=${cardClass()}>
      <div data-slot="card-header" class=${cardHeaderClass()}>
        <div data-slot="card-title" class=${cardTitleClass()}>Bar Chart - Active</div>
        <div data-slot="card-description" class=${cardDescriptionClass()}>January - June 2024</div>
      </div>
      <div data-slot="card-content" class=${cardContentClass()}>
        ${barChart({
          config: chartConfig,
          data: chartData,
          title: 'Visitors by browser',
          grid: { vertical: false },
          xAxis: {
            dataKey: 'browser',
            tickLine: false,
            tickMargin: 10,
            axisLine: false,
            tickFormatter: (value) => chartConfig[value as keyof typeof chartConfig]?.label,
          },
          tooltip: { cursor: false, hideLabel: true },
          bars: [{
            dataKey: 'visitors',
            strokeWidth: 2,
            radius: 8,
            shape: ({ index, datum, ...props }) => index === ACTIVE_INDEX
              ? chartRectangle({ ...props, fillOpacity: 0.8, stroke: String(datum.fill), strokeDasharray: 4, strokeDashoffset: 4 })
              : chartRectangle(props),
          }],
        })}
      </div>
      <div data-slot="card-footer" class=${cn(cardFooterClass(), 'flex-col items-start gap-2 text-sm')}>
        <div class="flex gap-2 leading-none font-medium">
          Trending up by 5.2% this month ${TrendingUp('h-4 w-4')}
        </div>
        <div class="leading-none text-muted-foreground">Showing total visitors for the last 6 months</div>
      </div>
    </div>
  `;
}
