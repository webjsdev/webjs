#!/usr/bin/env node
/**
 * Generate lib/ui/hugeicons.ts from an unpacked @hugeicons/core-free-icons
 * package (MIT), limited to the icon names passed on the command line. The
 * site does not depend on the package; fetch it once with `npm pack
 * @hugeicons/core-free-icons` in a scratch directory and untar it.
 *
 *   node scripts/gen-hugeicons.mjs <unpacked package dir> lib/ui/hugeicons.ts Name1Icon Name2Icon ...
 *
 * Pass the WHOLE list each time, since the output is rewritten.
 */
import { readFileSync, writeFileSync } from 'node:fs';
const [pkg, out, ...names] = process.argv.slice(2);
const attr = (k) => k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
let body = '';
for (const name of [...new Set(names)].sort()) {
  const index = readFileSync(`${pkg}/dist/esm/index.js`, 'utf8');
  const line = index.split('\n').find((l) => new RegExp(`default as ${name}[,\\s}]`).test(l));
  if (!line) throw new Error('no icon ' + name);
  const file = line.match(/from '\.\/([^']+)'/)[1];
  const src = readFileSync(`${pkg}/dist/esm/${file}`, 'utf8');
  const arr = src.slice(src.indexOf('['), src.lastIndexOf(']') + 1);
  const nodes = Function(`return ${arr}`)();
  const inner = nodes.map(([tag, props]) => {
    const a = Object.entries(props).filter(([k]) => k !== 'key').map(([k, v]) => k === 'strokeWidth' ? 'stroke-width=${sw}' : `${attr(k)}="${v}"`).join(' ');
    return `<${tag} ${a}></${tag}>`;
  }).join('');
  body += `export function ${name}(cls = '', sw = 1.5, opts: IconOptions = {}) {\n  return html\`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" fill="none" aria-hidden="true" data-icon=\${opts.icon ?? nothing} class=\${cls}>${inner}</svg>\`;\n}\n\n`;
}
const head = `import { html, nothing } from '@webjsdev/core';

/**
 * The Hugeicons glyphs the /ui home page and header use (#1666), generated from
 * @hugeicons/core-free-icons 4.4.0 (MIT, Copyright (c) 2025 Hugeicons; see
 * packages/ui/THIRD_PARTY_NOTICES.md). shadcn's site draws them through
 * <HugeiconsIcon>, which renders a 24px, stroke 1.5, currentColor SVG; each
 * function returns that same SVG with an optional class and stroke width
 * (shadcn passes strokeWidth={2} on most of them).
 *
 * Generated by scripts/gen-hugeicons.mjs, not hand-written: re-run it with
 * the full name list to add one. The kit's own icon libraries (D8) land separately.
 */

/**
 * What an icon helper takes beside its class and stroke width: \`icon\` is
 * shadcn's \`data-icon\` ("inline-start" | "inline-end"), which a button, badge
 * or input group reads to tighten its padding on the icon's side, as in
 * \`<HugeiconsIcon icon={...} data-icon="inline-start" />\`. The attribute
 * carries nothing else, so no icon names itself in it.
 */
export type IconOptions = { icon?: 'inline-start' | 'inline-end' };
`;
writeFileSync(out, head + '\n' + body.trimEnd() + '\n');
console.log('wrote', names.length, 'icons');
