/**
 * Generate the `.theme-<name>` classes for the /ui section (#1666), into
 * node_modules/.cache/ui-styles/themes.css, which public/ui-input.css imports
 * so they ride in public/ui.css on every /ui page.
 *
 * shadcn's site wears a theme by class: a docs preview passes
 * `previewClassName="theme-blue"` and the region repaints in blue, from the
 * `.theme-<name>` rules in its apps/v4/app/legacy-themes.css. This writes the
 * same rules for all 24 themes, from the kit's own data
 * (packages/ui/packages/registry/themes/themes.js, shadcn's values verbatim),
 * so the site and `webjsui init --preset` cannot drift:
 *
 *  - a base colour (`.theme-stone`) sets its whole palette;
 *  - an accent (`.theme-blue`) sets the neutral palette with the accent
 *    layered on, which is what shadcn's `.theme-blue` is.
 *
 * Each colour is written once as `light-dark(LIGHT, DARK)`, the site's token
 * form (see website/AGENTS.md "Style"), and a value that is the same in both
 * modes is written plain. The selector is `.ui-site .theme-<name>`, scoped to
 * the section like the rest of the /ui tokens.
 *
 * copy-registry.mjs runs this before every build of public/ui.css (all four
 * hooks: webjs.dev.before, webjs.dev.regenerate, webjs.start.before and the
 * Dockerfile), the same way it writes the scoped styles.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEMES, buildThemeVars, isBaseColor } from '../../packages/ui/packages/registry/themes/themes.js';

const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(here, '..');

export const THEMES_CSS = join(site, 'node_modules', '.cache', 'ui-styles', 'themes.css');

/** One token: plain when both modes agree, else light-dark(). */
function value(light, dark) {
  if (dark === undefined || light === dark) return light;
  if (light === undefined) return dark;
  return `light-dark(${light}, ${dark})`;
}

/**
 * The rule for one theme name.
 *
 * @param {string} name
 */
export function themeRule(name) {
  const { light, dark } = isBaseColor(name)
    ? buildThemeVars({ baseColor: name })
    : buildThemeVars({ baseColor: 'neutral', theme: name });
  const keys = [...new Set([...Object.keys(light), ...Object.keys(dark)])];
  const lines = keys.map((k) => `  --${k}: ${value(light[k], dark[k])};`);
  return `.ui-site .theme-${name} {\n${lines.join('\n')}\n}\n`;
}

/** The whole stylesheet: every theme, in shadcn's order. */
export function themeStylesheet() {
  return [
    '/* Generated by website/scripts/build-ui-themes.mjs from packages/ui/packages/registry/themes/themes.js. Do not edit. */',
    ...THEMES.map((t) => themeRule(t.name)),
  ].join('\n');
}

/** Write the stylesheet, touching the file only when its content changes. */
export function writeThemeStyles() {
  const css = themeStylesheet();
  mkdirSync(dirname(THEMES_CSS), { recursive: true });
  try {
    if (readFileSync(THEMES_CSS, 'utf8') === css) return false;
  } catch {
    /* missing: fall through and write */
  }
  writeFileSync(THEMES_CSS, css);
  return true;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeThemeStyles();
  console.log(`[build-ui-themes] wrote ${THEMES.length} theme classes`);
}
